def lookup_isp(plmn, default=''):
    """
    Look up mobile operator (ISP) brand name by PLMN (MCC + MNC).
    Supports normalized 2-digit and 3-digit MNC matching.
    Returns matched operator name, or default if not found.
    """
    if not plmn:
        return default
    code = str(plmn).strip()
    if code in ISP_MAP:
        return ISP_MAP[code]
    # If 4 digits (e.g. 5101 where MNC was 1 digit), try padding with 0 (51001)
    if len(code) == 4 and code[:3].isdigit() and code[3:].isdigit():
        padded = code[:3] + "0" + code[3]
        if padded in ISP_MAP:
            return ISP_MAP[padded]
    # If 5 digits with leading 0 in MNC (e.g. 51001), try unpadding (5101)
    elif len(code) == 5 and code[:3].isdigit() and code[3] == "0":
        unpadded = code[:3] + code[4]
        if unpadded in ISP_MAP:
            return ISP_MAP[unpadded]
    return default

